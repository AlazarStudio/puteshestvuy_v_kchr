/** Альтернативный текст изображений: единственная копия правил в проекте */

/**
 * Подпись фотографии в галерее объекта: «Домбайская поляна — фото 3».
 * Название приходит из данных и может быть пустым — тогда остаётся нейтральное «Фото 3»:
 * порядковый номер полезнее пустого alt, который скринридер просто пропустит.
 * @param {string} title название объекта из данных
 * @param {number} index номер фотографии, считается с 1
 * @returns {string}
 */
export function photoAlt(title, index) {
  const name = typeof title === 'string' ? title.trim() : ''
  return name ? `${name} — фото ${index}` : `Фото ${index}`
}

/**
 * Подпись миниатюры в модальной галерее — она переключает крупное фото, а не несёт содержание.
 * @param {number} index номер фотографии, считается с 1
 * @returns {string}
 */
export function thumbAlt(index) {
  return `Миниатюра ${index}`
}
